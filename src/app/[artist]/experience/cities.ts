const fold = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .split(",")[0]
    .trim();

/** [lat, lon] for a city name as people write it ("Brooklyn, NY", "Ciudad de México"), or null. */
export function locate(city: string): [number, number] | null {
  return CITIES[fold(city)] ?? null;
}
